const customRoleRegistry = new Map<string, RoleTemplate>();

/**
 * Register roles created on demand (ids start with "custom_").
 * Client: call with roles loaded from localStorage / MeetingConfig.customRoles.
 * Server: call with config.customRoles at the start of each request.
 */
export function registerCustomRoles(roles: RoleTemplate[] | undefined): void {
  for (const r of roles ?? []) customRoleRegistry.set(r.id, r);
}

export function getCustomRoles(): RoleTemplate[] {
  return [...customRoleRegistry.values()];
}

/** Resolve a role: static catalog first, then custom roles. */
export function getRole(id: string): RoleTemplate | undefined {
  return ROLES.find((r) => r.id === id) ?? customRoleRegistry.get(id);
}
